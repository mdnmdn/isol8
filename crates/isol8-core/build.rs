use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    // Workspace root: crates/isol8-core -> ../..
    let workspace_root = manifest_dir
        .parent()
        .and_then(|p| p.parent())
        .expect("workspace root")
        .to_path_buf();
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());

    emit_embedded(
        &workspace_root,
        &out_dir,
        "profiles",
        "profiles_embedded.rs",
        "BUILTIN_PROFILES",
        "Built-in profile layers embedded at compile time.",
    );
    emit_embedded(
        &workspace_root,
        &out_dir,
        "recipes",
        "recipes_embedded.rs",
        "BUILTIN_RECIPES",
        "Built-in recipes embedded at compile time.",
    );

    let target_os = env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    if target_os == "windows" {
        embed_winhook_dll(&workspace_root, &out_dir);
    }
}

fn emit_embedded(
    workspace_root: &Path,
    out_dir: &Path,
    tree: &str,
    out_name: &str,
    const_name: &str,
    doc: &str,
) {
    let dir = workspace_root.join(tree);
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut entries: Vec<(String, String)> = Vec::new();
    collect_toml(&dir, &dir, &mut entries);
    entries.sort_by(|a, b| a.0.cmp(&b.0));

    let mut code = format!(
        "// Generated by build.rs — do not edit.\n\
         /// {doc}\n\
         pub const {const_name}: &[(&str, &str)] = &[\n"
    );
    for (name, body) in &entries {
        // Embed body as a raw string; use many # to avoid conflicts.
        let lit = format!("r##########\"{body}\"##########");
        code.push_str(&format!("    (\"{name}\", {lit}),\n"));
    }
    code.push_str("];\n");

    fs::write(out_dir.join(out_name), code).unwrap_or_else(|e| {
        panic!("write {out_name}: {e}");
    });
}

fn collect_toml(base: &Path, dir: &Path, out: &mut Vec<(String, String)>) {
    let read_dir = match fs::read_dir(dir) {
        Ok(d) => d,
        Err(_) => return,
    };
    for entry in read_dir.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect_toml(base, &path, out);
        } else if path.extension().and_then(|e| e.to_str()) == Some("toml") {
            let rel = path.strip_prefix(base).unwrap();
            let name = rel.with_extension("").to_string_lossy().replace('\\', "/");
            let body = fs::read_to_string(&path).unwrap_or_else(|e| {
                panic!("read {}: {e}", path.display());
            });
            out.push((name, body));
        }
    }
}

fn embed_winhook_dll(workspace_root: &Path, out_dir: &Path) {
    println!(
        "cargo:rerun-if-changed={}",
        workspace_root.join("crates/isol8-winhook").display()
    );
    println!("cargo:rerun-if-env-changed=ISOL8_WINHOOK_DLL");

    let target = env::var("TARGET").expect("TARGET");
    let profile = env::var("PROFILE").expect("PROFILE");
    let dll_src =
        locate_winhook_dll(workspace_root, &target, &profile).unwrap_or_else(|e| panic!("{e}"));
    let dll_dst = out_dir.join("isol8-winhook.dll");
    fs::copy(&dll_src, &dll_dst).expect("copy winhook dll into OUT_DIR");

    let code = "// Generated by build.rs — do not edit.\n\
pub const EMBEDDED_WINHOOK_DLL: &[u8] = include_bytes!(concat!(env!(\"OUT_DIR\"), \"/isol8-winhook.dll\"));\n";
    fs::write(out_dir.join("winhook_embedded.rs"), code).expect("write winhook_embedded.rs");
}

fn winhook_dll_candidates(workspace_root: &Path, target: &str, profile: &str) -> Vec<PathBuf> {
    vec![
        workspace_root.join(format!("target/{target}/{profile}/isol8_winhook.dll")),
        workspace_root.join(format!(
            "target/isol8-winhook-embed/{target}/{profile}/isol8_winhook.dll"
        )),
    ]
}

fn locate_winhook_dll(
    workspace_root: &Path,
    target: &str,
    profile: &str,
) -> Result<PathBuf, String> {
    if let Ok(path) = env::var("ISOL8_WINHOOK_DLL") {
        let path = PathBuf::from(path);
        if path.is_file() {
            return Ok(path);
        }
        return Err(format!(
            "ISOL8_WINHOOK_DLL points to a missing file: {}",
            path.display()
        ));
    }

    for built in winhook_dll_candidates(workspace_root, target, profile) {
        if built.is_file() {
            return Ok(built);
        }
    }

    build_winhook_dll(workspace_root, target, profile)?;

    for built in winhook_dll_candidates(workspace_root, target, profile) {
        if built.is_file() {
            return Ok(built);
        }
    }

    Err(format!(
        "failed to locate isol8_winhook.dll for {target}/{profile}; \
         install a Windows C toolchain (MSVC or MinGW-w64 gcc), or set ISOL8_WINHOOK_DLL"
    ))
}

fn build_winhook_dll(workspace_root: &Path, target: &str, profile: &str) -> Result<(), String> {
    use std::process::Command;

    // Separate target dir so nested `cargo build` does not deadlock on the parent lock.
    let nested_target = workspace_root.join("target/isol8-winhook-embed");
    let mut cmd = Command::new(env::var("CARGO").unwrap_or_else(|_| "cargo".into()));
    cmd.current_dir(workspace_root)
        .env("CARGO_TARGET_DIR", &nested_target)
        .arg("build")
        .arg("-p")
        .arg("isol8-winhook")
        .arg("--target")
        .arg(target);
    if profile == "release" {
        cmd.arg("--release");
    }
    let status = cmd
        .status()
        .map_err(|e| format!("failed to run cargo build -p isol8-winhook: {e}"))?;
    if !status.success() {
        return Err(
            "cargo build -p isol8-winhook failed; Windows path enforcement requires the hook DLL"
                .into(),
        );
    }
    Ok(())
}
